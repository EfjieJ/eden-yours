  function detectLang() {
    // Lien explicite ?lang=fr|en (portail, liens de jeux) : il a priorité et devient le choix enregistré.
    try {
      var q = new URLSearchParams(window.location.search).get("lang");
      if (q === "fr" || q === "en") {
        try { localStorage.setItem(STORAGE_KEY, q); } catch (e) {}
        return q;
      }
    } catch (e) {}
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored === "fr" || stored === "en") return stored;
    } catch (e) {}
    // First visit / no preference: follow the visitor's phone/browser language
    // (French if any preferred language is French, otherwise English).
    try {
      var prefs = (navigator.languages && navigator.languages.length)
        ? navigator.languages : [navigator.language || navigator.userLanguage || ""];
      for (var i = 0; i < prefs.length; i++) {
        var code = String(prefs[i] || "").toLowerCase();
        if (code.indexOf("fr") === 0) return "fr";
        if (code.indexOf("en") === 0) return "en";
      }
    } catch (e) {}
    return "en";
  }

  var lang = detectLang();
  var listeners = [];

  function interpolate(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{\{(\w+)\}\}/g, function (_, k) {
      return vars[k] != null ? String(vars[k]) : "";
    });
  }

  function t(key, vars) {
    var pack = dict[lang] || dict.fr;
    var val = pack[key];
    if (val == null) val = (dict.fr && dict.fr[key]) || key;
    return interpolate(val, vars);
  }

  function applyAttr(el, attr, value) {
    if (value == null) return;
    if (attr === "text") el.textContent = value;
    else if (attr === "html") el.innerHTML = value;
    else el.setAttribute(attr, value);
  }

  function apply() {
    document.documentElement.lang = lang === "en" ? "en" : "fr-CA";

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      applyAttr(el, "text", t(el.getAttribute("data-i18n")));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      applyAttr(el, "html", t(el.getAttribute("data-i18n-html")));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-title");
      var val = t(key);
      if (el.tagName === "TITLE") {
        document.title = val;
        el.textContent = val;
      } else {
        el.setAttribute("title", val);
      }
    });
    document.querySelectorAll('meta[name="description"][data-i18n-content]').forEach(function (el) {
      el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
    });
    document.querySelectorAll('meta[property="og:title"][data-i18n-content], meta[property="og:description"][data-i18n-content], meta[name="twitter:title"][data-i18n-content], meta[name="twitter:description"][data-i18n-content], meta[property="og:image:alt"][data-i18n-content], meta[name="twitter:image:alt"][data-i18n-content]').forEach(function (el) {
      el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
    });
    var ogLocale = document.querySelector('meta[property="og:locale"]');
    if (ogLocale) ogLocale.setAttribute("content", lang === "en" ? "en_US" : "fr_CA");

    // Taglines from config override only if no data-i18n; we prefer i18n
    document.querySelectorAll("[data-tagline]").forEach(function (el) {
      if (!el.hasAttribute("data-i18n")) el.textContent = t("common.tagline");
    });

    // Liens vers les jeux : on garde la langue choisie (?lang=fr|en)
    document.querySelectorAll("[data-lang-href]").forEach(function (el) {
      var base = el.getAttribute("data-lang-href");
      var hash = "";
      var h = base.indexOf("#");
      if (h !== -1) { hash = base.slice(h); base = base.slice(0, h); }
      el.setAttribute("href", base + (base.indexOf("?") === -1 ? "?" : "&") + "lang=" + lang + hash);
    });

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      var l = btn.getAttribute("data-set-lang");
      var active = l === lang;
      btn.classList.toggle("is-active", active);
      btn.setAttribute("aria-pressed", active ? "true" : "false");
    });

    listeners.forEach(function (fn) {
      try { fn(lang); } catch (e) { console.error(e); }
    });
  }

  function setLang(next) {
    if (next !== "fr" && next !== "en") return;
    if (next === lang) {
      apply();
      return;
    }
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    apply();
  }

  function onChange(fn) {
    if (typeof fn === "function") listeners.push(fn);
  }

  function initSwitcher() {
    document.querySelectorAll("[data-set-lang]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        setLang(btn.getAttribute("data-set-lang"));
      });
    });
  }

  window.EdenI18n = {
    t: t,
    apply: apply,
    setLang: setLang,
    getLang: function () { return lang; },
    onChange: onChange,
    dict: dict
  };

  function boot() {
    initSwitcher();
    apply();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
